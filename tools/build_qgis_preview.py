"""Build an isolated plugin preview using the same core algorithm with native QGIS geometry.

The installed plugin and source checkout are never modified. The bundle contains
only the shared engine and a QGIS backend import; it does not require Shapely,
Rasterio, Pyogrio, or terminal installation inside QGIS.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import zipfile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--plugin-source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = args.output.resolve()
    if output.exists() and any(output.iterdir()):
        raise RuntimeError("Output directory must be new or empty")
    plugin = output / "TerraLink"
    plugin.mkdir(parents=True)
    for p in args.plugin_source.iterdir():
        if p.is_file() and p.suffix.lower() in {".py", ".txt", ".md", ".png", ".ui"}:
            shutil.copyfile(p, plugin / p.name)
    vendor = plugin / "_vendor"
    (vendor / "terralink_core/geometry").mkdir(parents=True)
    (vendor / "__init__.py").write_text("")
    (vendor / "terralink_core/__init__.py").write_text(
        '"""Pinned TerraLink shared numerical engine for QGIS."""\n'
    )
    shutil.copytree(
        root / "src/terralink_core/_engine",
        vendor / "terralink_core/_engine",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    engine = vendor / "terralink_core/_engine/analysis_vector.py"
    text = engine.read_text().replace(
        "from ..geometry.compat import QVariant, QUrl",
        "from qgis.PyQt.QtCore import QVariant, QUrl",
    )
    text = text.replace("from ..geometry.compat import (", "from qgis.core import (")
    engine.write_text(text)
    shutil.copyfile(
        args.plugin_source / "utils.py", vendor / "terralink_core/_engine/utils.py"
    )
    (
        plugin / "analysis_vector.py"
    ).write_text('''"""QGIS adapter for the version-pinned TerraLink shared algorithm.
Generated by terralink-core/tools/build_qgis_preview.py; do not edit bundled code.
"""
import sys
from ._vendor.terralink_core._engine import analysis_vector as _engine
sys.modules[__name__] = _engine
''')
    metadata = plugin / "metadata.txt"
    text = metadata.read_text()
    text = text.replace("version=1.8.3", "version=1.9.0")
    text = text.replace(
        "changelog=",
        "changelog=v1.9.0 (experimental): Bundle the shared TerraLink core with native QGIS geometry and preserve the 1.8.3 analysis baseline. ",
        1,
    )
    if "experimental=" in text:
        import re

        text = re.sub(
            r"^experimental=.*$", "experimental=True", text, flags=re.MULTILINE
        )
    else:
        text += "\nexperimental=True\n"
    metadata.write_text(text)
    readme = plugin / "readme.md"
    if readme.exists():
        readme.write_text(
            readme.read_text().replace(
                "# TerraLink QGIS Plugin 1.8.3",
                "# TerraLink QGIS Plugin 1.9.0 (experimental shared-core preview)\n\nThis preview bundles the shared algorithm from https://github.com/sorus-tools/terralink-core with native QGIS geometry. The released 1.8.3 behavior and documentation remain the baseline below.",
            )
        )
    shutil.copyfile(root / "LICENSE", plugin / "LICENSE")
    shutil.copyfile(root / "NOTICE.md", plugin / "CORE_NOTICE.md")
    provenance = json.loads((root / "source-provenance.json").read_text())
    provenance.update(
        core_version="0.1.0a1",
        status="experimental preview",
        bundled_files={
            str(p.relative_to(vendor)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(vendor.rglob("*"))
            if p.is_file()
        },
    )
    (plugin / "engine-bundle.json").write_text(json.dumps(provenance, indent=2) + "\n")
    archive = output / "TerraLink.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(plugin.rglob("*")):
            if path.is_file():
                z.write(path, str(path.relative_to(output)))
    print(archive)


if __name__ == "__main__":
    main()
